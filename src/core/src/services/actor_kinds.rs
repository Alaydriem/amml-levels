    pub fn classify(actor_type: u32) -> ActorClass {
        let kind = (actor_type & 0xFF) as u8;
        if kind == Self::PLAYER_KIND {
            ActorClass::Player
        } else if actor_type & Self::MONSTER_BIT != 0 || Self::HOSTILE_WITHOUT_MONSTER_BIT.contains(&kind) {
            ActorClass::Hostile
        } else if actor_type & Self::MOB_BIT != 0 {
            ActorClass::Passive
        } else {
            ActorClass::Other
        }
    }

    pub fn name(actor_type: u32) -> Option<&'static str> {
        let kind = (actor_type & 0xFF) as u8;
        Self::NAMES.binary_search_by_key(&kind, |entry| entry.0).ok().map(|i| Self::NAMES[i].1)
    }
